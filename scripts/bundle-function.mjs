// Builds one paste-ready file for the Supabase dashboard editor from
// supabase/functions/submit-quote/{lib.ts,index.ts}.
// Usage: npm run bundle-function  ->  dist/submit-quote.ts
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../supabase/functions/submit-quote/", import.meta.url);
const lib = readFileSync(new URL("lib.ts", dir), "utf8");
let index = readFileSync(new URL("index.ts", dir), "utf8");

const importLine = /^import \{[^}]*\} from "\.\/lib\.ts";\n/m;
if (!importLine.test(index)) throw new Error("index.ts no longer imports ./lib.ts as expected");
index = index.replace(importLine, "");
const libBody = lib.replace(/^(\/\/.*\n|\s*\n)*/, "");
const marker = 'import postgres from "npm:postgres@3.4.5";\n';
if (!index.includes(marker)) throw new Error("postgres import not found in index.ts");
const out = [
  "// Single-file build of supabase/functions/submit-quote (index.ts + lib.ts) for",
  "// pasting into the Supabase dashboard editor. Generated by scripts/bundle-function.mjs.",
  "",
  index.replace(marker, marker + "\n// ---- validation and pricing (lib.ts) ----\n\n" + libBody + "\n// ---- HTTP handler (index.ts) ----\n"),
].join("\n");
mkdirSync(new URL("../dist/", import.meta.url), { recursive: true });
writeFileSync(new URL("../dist/submit-quote.ts", import.meta.url), out);
console.log("wrote dist/submit-quote.ts");
