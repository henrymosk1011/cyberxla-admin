// Builds one paste-ready file for the Supabase dashboard editor from
// supabase/functions/<name>/index.ts and everything it imports from this repo
// (its lib.ts and ../_shared/*.ts). npm: and jsr: imports stay as they are.
// Usage: npm run bundle-function                    ->  dist/submit-quote.ts
//        npm run bundle-report-action               ->  dist/report-action.ts
//        node scripts/bundle-function.mjs quote-action  ->  dist/quote-action.ts
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../supabase/functions/", import.meta.url));
const name = process.argv[2] ?? "submit-quote";
const entry = join(root, name, "index.ts");
if (!existsSync(entry)) throw new Error(`no function named ${name}`);

const LOCAL = /^import\s+(?:type\s+)?\{[^}]*\}\s+from\s+"(\.{1,2}\/[^"]+\.ts)";\n/gm;
const seen = new Set();
const parts = [];
function add(file) {
  if (seen.has(file)) return;
  seen.add(file);
  const src = readFileSync(file, "utf8");
  for (const m of src.matchAll(LOCAL)) add(join(dirname(file), m[1]));
  const body = src.replace(LOCAL, "");
  parts.push(file === entry ? `// ---- ${relative(root, file)} ----\n${body}` : `// ---- ${relative(root, file)} ----\n${body.replace(/^(\/\/.*\n|\s*\n)*/, "")}`);
}
add(entry);
const out = [
  `// Single-file build of supabase/functions/${name} and what it imports, for`,
  "// pasting into the Supabase dashboard editor. Generated by scripts/bundle-function.mjs.",
  "",
  ...parts,
].join("\n");
mkdirSync(new URL("../dist/", import.meta.url), { recursive: true });
writeFileSync(new URL(`../dist/${name}.ts`, import.meta.url), out);
console.log(`wrote dist/${name}.ts`);
