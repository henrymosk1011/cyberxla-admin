// Builds one paste-ready file for the Supabase dashboard editor from
// supabase/functions/<name>/{lib.ts,index.ts}.
// Usage: npm run bundle-function                    ->  dist/submit-quote.ts
//        npm run bundle-report-action               ->  dist/report-action.ts
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const LABELS = { "submit-quote": "validation and pricing", "report-action": "request checks and rules" };
const name = process.argv[2] ?? "submit-quote";
if (!LABELS[name]) throw new Error(`unknown function ${name} (one of: ${Object.keys(LABELS).join(", ")})`);

const dir = new URL(`../supabase/functions/${name}/`, import.meta.url);
const lib = readFileSync(new URL("lib.ts", dir), "utf8");
const index = readFileSync(new URL("index.ts", dir), "utf8");

const importLine = /^import \{[^}]*\} from "\.\/lib\.ts";\n/m;
if (!importLine.test(index)) throw new Error("index.ts no longer imports ./lib.ts as expected");
const libBody = lib.replace(/^(\/\/.*\n|\s*\n)*/, "");
const out = [
  `// Single-file build of supabase/functions/${name} (index.ts + lib.ts) for`,
  "// pasting into the Supabase dashboard editor. Generated by scripts/bundle-function.mjs.",
  "",
  index.replace(importLine, () => `\n// ---- ${LABELS[name]} (lib.ts) ----\n\n${libBody}\n// ---- HTTP handler (index.ts) ----\n`),
].join("\n");
mkdirSync(new URL("../dist/", import.meta.url), { recursive: true });
writeFileSync(new URL(`../dist/${name}.ts`, import.meta.url), out);
console.log(`wrote dist/${name}.ts`);
